#!/usr/bin/env python3
"""Write the operator-owned boundary policies in this directory.

Deliberately independent of the ``yard`` package: the boundaries state what
Alex allows, and the prover checks yard's rendered policies against them. If
the renderer has a bug, it must not also move the boundary. Edit the lists
below (and review the diff) to change a boundary; CI never regenerates them.

Run: python3 policies/boundaries/make_boundaries.py
"""

import ipaddress
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

NEVER_V4 = ["0.0.0.0/8", "10.0.0.0/8", "100.64.0.0/10", "127.0.0.0/8",
            "169.254.0.0/16", "224.0.0.0/3"]

OPEN_TLDS = ["com", "org", "net", "io", "dev", "ai", "app", "co", "sh", "me", "rs",
             "so", "gg", "xyz", "cloud", "tech", "info", "edu", "gov", "us", "uk",
             "de", "eu", "ch"]
APEX = ["github.com", "pypi.org", "npmjs.org", "npmjs.com", "crates.io", "go.dev",
        "golang.org", "rubygems.org", "nodejs.org", "python.org", "docker.io",
        "ghcr.io", "quay.io", "openrouter.ai"]

# Hosts each credential may ever be sent to.
CREDENTIAL_HOSTS = {
    "github": ["github.com", "api.github.com"],
    "openrouter": ["openrouter.ai"],
    "typesafe": ["api.typesafe.ai"],
    "selftest-canary": ["postman-echo.com"],
}
# Registries a deny-mode job may be allowlisted for (project config).
REGISTRY_HOSTS = ["pypi.org", "files.pythonhosted.org", "registry.npmjs.org",
                  "crates.io", "static.crates.io", "index.crates.io", "proxy.golang.org"]

GIT, GH, CURL, CLAUDE, ANY = "/usr/bin/git", "/usr/bin/gh", "/usr/bin/curl", "/usr/local/bin/claude", "/**"


def public_v4():
    nets = [ipaddress.ip_network("0.0.0.0/0")]
    for ex in map(ipaddress.ip_network, NEVER_V4):
        out = []
        for n in nets:
            if not n.overlaps(ex):
                out.append(n)
            elif ex.subnet_of(n):
                out.extend(n.address_exclude(ex))
        nets = out
    return [str(n) for n in sorted(ipaddress.collapse_addresses(nets))]


IPS = public_v4()
NO_PUT = [{"method": "PUT", "path": "/**"}]


def ep(host, ports=(443,), deny=None, path=None):
    e = {"host": host}
    if len(ports) == 1:
        e["port"] = ports[0]
    else:
        e["ports"] = list(ports)
    if path:
        e["path"] = path
    e.update({"protocol": "rest", "enforcement": "enforce", "access": "full"})
    if deny:
        e["deny_rules"] = deny
    e["allowed_ips"] = IPS
    return e


def rule(endpoints, binaries):
    return {"endpoints": endpoints, "binaries": [{"path": b} for b in binaries]}


def github_eps(ports=(443,)):
    # Any path on GitHub except PUT on the REST API (the PR merge endpoint
    # is PUT /repos/{owner}/{repo}/pulls/{number}/merge).
    return [ep("github.com", ports), ep("api.github.com", ports, deny=NO_PUT)]


def covered(host):
    labels = host.split(".")
    return len(labels) >= 3 and labels[-1] in OPEN_TLDS


def network_boundary(mode):
    filesystem = {
        "include_workdir": True,
        "read_only": ["/usr", "/lib", "/etc", "/bin", "/proc", "/dev/urandom", "/var/log", "/opt"],
        "read_write": ["/tmp", "/dev/null", "/var/tmp"],
    }
    rules = {
        "anthropic": rule([ep("api.anthropic.com")], [CLAUDE]),
        "github_tools": rule(github_eps(), [GIT, GH, CURL]),
    }
    services = [ep(h) for k, hs in CREDENTIAL_HOSTS.items() if k != "github" for h in hs]
    if mode == "open":
        hosts = [f"**.*.{t}" for t in OPEN_TLDS] + APEX
        anyb = [ep(h, (80, 443)) for h in hosts if h not in ("github.com",)]
        anyb += github_eps((80, 443))
        rules["any_binary"] = rule(anyb + [ep(h, (80, 443)) for h in REGISTRY_HOSTS
                                          if h not in hosts and not covered(h)], [ANY])
    else:
        rules["any_binary"] = rule([ep(h) for h in REGISTRY_HOSTS] + services, [ANY])
    return {
        "version": 1,
        "filesystem_policy": filesystem,
        "landlock": {"compatibility": "hard_requirement"},
        "process": {"run_as_user": "1000", "run_as_group": "1000"},
        "network_policies": rules,
    }


def credential_boundary(kind):
    hosts = CREDENTIAL_HOSTS[kind]
    eps = github_eps() if kind == "github" else [ep(h) for h in hosts]
    return {"version": 1, "network_policies": {f"{kind}_credential": rule(eps, [ANY])}}


def write(name, doc):
    path = os.path.join(HERE, name)
    with open(path, "w") as fh:
        fh.write("# Operator-owned boundary. Generated by make_boundaries.py; review diffs.\n")
        # JSON is valid YAML and keeps this script dependency-free.
        json.dump(doc, fh, indent=2)
        fh.write("\n")


if __name__ == "__main__":
    write("network-open.yaml", network_boundary("open"))
    write("network-deny.yaml", network_boundary("deny"))
    for kind in CREDENTIAL_HOSTS:
        write(f"credential-{kind}.yaml", credential_boundary(kind))
